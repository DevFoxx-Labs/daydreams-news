function buildStory(seed: Seed): Story {
  const category = cat(seed.cat);
  const parent = parentOf[seed.cat] ?? category;
  const author = authorBySlug[seed.author ?? "desk-report"] ?? authors[0];
  const isSubCategory = parent.slug !== category.slug;

  return {
    id: seed.id,
    slug: seed.slug,
    type: seed.type ?? "article",
    title: seed.title,
    deck: seed.deck,
    highlights: seed.highlights,
    category: parent,
    subCategory: isSubCategory ? category : undefined,
    state: seed.state,
    city: seed.city,
    image: {
      scene: seed.scene,
      alt: seed.title,
      width: 1600,
      height: 900,
      caption:
        seed.id === "1001"
          ? "घने कोहरे के बीच सुबह का नज़ारा।"
          : `${category.name} से जुड़ी प्रतीकात्मक तस्वीर।`,
      credit: "ख़बर सेतु",
      isFile: true,
    },
    authors: [author],
    dateline: seed.dateline,
    publishedAt: minutesAgo(seed.mins),
    updatedAt:
      seed.updatedMins !== undefined ? minutesAgo(seed.updatedMins) : undefined,
    readMinutes: seed.readMinutes ?? 3,
    body: seed.body ?? demoBody(seed),
    tags: seed.tags,
    isLive: seed.live,
    isBreaking: seed.breaking,
    isSponsored: seed.sponsored,
    videoId: seed.type === "video" ? `demo-${seed.id}` : undefined,
    videoDuration: seed.dur,
    photoCount: seed.photos,
    views: seed.views,
    corrections:
      seed.id === "1025"
        ? [
            {
              text: "इस ख़बर के पहले संस्करण में लागू होने का वर्ष ग़लत छप गया था। सुधार कर दिया गया है।",
              correctedAt: minutesAgo(120),
            },
          ]
        : undefined,
  };
}

/** All demo stories, newest first. */
export const stories: Story[] = seeds
  .map(buildStory)
  .sort((a, b) => Date.parse(b.publishedAt) - Date.parse(a.publishedAt));
